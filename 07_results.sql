-- 1. CREATE TABLE: RESULTS

CREATE TABLE Results (
    result_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id NUMBER UNIQUE NOT NULL,
    marks_obtained NUMBER(5,2)
        CHECK (marks_obtained >= 0),
    total_marks NUMBER(5,2) DEFAULT 100,
    grade CHAR(2),
    exam_date DATE,

    CONSTRAINT fk_results_enrollment
        FOREIGN KEY (enrollment_id)
        REFERENCES Enrollment(enrollment_id)
);

